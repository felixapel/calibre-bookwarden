package findings

import "testing"

func TestCanonicalISBN(t *testing.T) {
	for _, tt := range []struct{ raw, want string }{
		{"0-306-40615-2", "9780306406157"}, {"9780306406157", "9780306406157"},
		{"0-8044-2957-X", "9780804429573"}, {"0-8044-2957-x", "9780804429573"},
		{"9791090636071", "9791090636071"}, {" ISBN: 0-306-40615-2 ", "9780306406157"},
		{"urn:isbn:9780306406157", "9780306406157"}, {"ISBN 9780306406157", "9780306406157"},
		{"9780306406158", ""}, {"0306406153", ""}, {"1234567890128", ""},
		{"03064X6152", ""}, {"book9780306406157", ""}, {"9780306406157!", ""},
		{"9780306406157/9780804429573", ""}, {"", ""},
	} {
		t.Run(tt.raw, func(t *testing.T) {
			got, ok := CanonicalISBN(tt.raw)
			if got != tt.want || ok != (tt.want != "") {
				t.Fatalf("CanonicalISBN(%q) = %q, %v; want %q", tt.raw, got, ok, tt.want)
			}
		})
	}
}
